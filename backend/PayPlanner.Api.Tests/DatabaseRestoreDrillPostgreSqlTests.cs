using Npgsql;
using PayPlanner.Api.Services;
using Xunit;

namespace PayPlanner.Api.Tests;

public sealed class DatabaseRestoreDrillPostgreSqlTests
{
    [Fact]
    public async Task PostgreSqlDrill_AcceptsOnlyAnEmptyDisposableDatabase()
    {
        var connectionString = Environment.GetEnvironmentVariable("PAYPLANNER_TEST_POSTGRES");
        if (string.IsNullOrWhiteSpace(connectionString))
        {
            Assert.False(string.Equals(Environment.GetEnvironmentVariable("CI"), "true", StringComparison.OrdinalIgnoreCase),
                "PAYPLANNER_TEST_POSTGRES must be configured in CI.");
            return;
        }

        var databaseName = "payplanner_restore_test_" + Guid.NewGuid().ToString("N");
        var adminBuilder = new NpgsqlConnectionStringBuilder(connectionString) { Database = "postgres", Pooling = false };
        await using var admin = new NpgsqlConnection(adminBuilder.ConnectionString);
        await admin.OpenAsync();
        await using (var create = admin.CreateCommand())
        {
            create.CommandText = $"CREATE DATABASE \"{databaseName}\"";
            await create.ExecuteNonQueryAsync();
        }

        try
        {
            var targetBuilder = new NpgsqlConnectionStringBuilder(adminBuilder.ConnectionString) { Database = databaseName };
            await DatabaseRestoreDrillService.EnsureEmptyPostgreSqlTargetAsync(targetBuilder.ConnectionString, CancellationToken.None);

            await using var target = new NpgsqlConnection(targetBuilder.ConnectionString);
            await target.OpenAsync();
            await using (var seed = target.CreateCommand())
            {
                seed.CommandText = "CREATE TABLE public.existing_data (id integer PRIMARY KEY); INSERT INTO public.existing_data VALUES (42);";
                await seed.ExecuteNonQueryAsync();
            }

            await Assert.ThrowsAsync<InvalidOperationException>(() =>
                DatabaseRestoreDrillService.EnsureEmptyPostgreSqlTargetAsync(targetBuilder.ConnectionString, CancellationToken.None));
            await using var count = target.CreateCommand();
            count.CommandText = "SELECT COUNT(*) FROM public.existing_data WHERE id = 42";
            Assert.Equal(1L, await count.ExecuteScalarAsync());

            await using (var createRestoreData = target.CreateCommand())
            {
                createRestoreData.CommandText = """
                    CREATE TABLE "SystemSettings" (
                        "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        "Key" text NOT NULL UNIQUE, "Value" text NOT NULL,
                        "CreatedAt" timestamp NOT NULL, "UpdatedAt" timestamp NOT NULL);
                    CREATE TABLE "NotificationDeliveries" (
                        "Id" integer PRIMARY KEY, "Channel" text NOT NULL,
                        "Status" text NOT NULL, "Error" text NULL);
                    CREATE TABLE "NotificationSenders" (
                        "Id" integer PRIMARY KEY, "Channel" text NOT NULL, "IsEnabled" boolean NOT NULL,
                        "ConfigJson" text NOT NULL, "UpdatedAt" timestamp NULL);
                    INSERT INTO "NotificationSenders" ("Id", "Channel", "IsEnabled", "ConfigJson")
                    VALUES (1, 'email', true, '{"smtpHost":"test-only.invalid"}'), (2, 'telegram', true, '{"test":true}');
                    INSERT INTO "SystemSettings" ("Key", "Value", "CreatedAt", "UpdatedAt")
                    VALUES ('notifications.email.smtpPassword', 'secret', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);
                    INSERT INTO "NotificationDeliveries" ("Id", "Channel", "Status")
                    VALUES (1, 'email', 'failed'), (2, 'email', 'pending'), (3, 'email', 'sent'), (4, 'telegram', 'failed');
                    """;
                await createRestoreData.ExecuteNonQueryAsync();
            }

            await DatabaseRestoreDrillService.SanitizeRestoredPostgreSqlAsync(target, CancellationToken.None);
            await DatabaseRestoreDrillService.SanitizeRestoredPostgreSqlAsync(target, CancellationToken.None);
            await using (var readSettings = target.CreateCommand())
            {
                readSettings.CommandText = "SELECT \"Value\" FROM \"SystemSettings\" WHERE \"Key\" = 'notifications.email.enabled'";
                Assert.Equal("false", await readSettings.ExecuteScalarAsync());
                readSettings.CommandText = "SELECT \"Value\" FROM \"SystemSettings\" WHERE \"Key\" = 'notifications.email.smtpPassword'";
                Assert.Equal(string.Empty, await readSettings.ExecuteScalarAsync());
                readSettings.CommandText = "SELECT \"ConfigJson\" FROM \"NotificationSenders\" WHERE \"Channel\" = 'email' AND NOT \"IsEnabled\"";
                Assert.Equal("{}", await readSettings.ExecuteScalarAsync());
                readSettings.CommandText = "SELECT \"ConfigJson\" FROM \"NotificationSenders\" WHERE \"Channel\" = 'telegram' AND \"IsEnabled\"";
                Assert.Equal("{\"test\":true}", await readSettings.ExecuteScalarAsync());
            }
            await using (var readDeliveries = target.CreateCommand())
            {
                readDeliveries.CommandText = "SELECT \"Status\" FROM \"NotificationDeliveries\" ORDER BY \"Id\"";
                await using var reader = await readDeliveries.ExecuteReaderAsync();
                var statuses = new List<string>();
                while (await reader.ReadAsync()) statuses.Add(reader.GetString(0));
                Assert.Equal(["skipped", "skipped", "sent", "failed"], statuses);
            }
        }
        finally
        {
            await using var terminate = admin.CreateCommand();
            terminate.CommandText = "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = @databaseName AND pid <> pg_backend_pid()";
            terminate.Parameters.AddWithValue("databaseName", databaseName);
            await terminate.ExecuteNonQueryAsync();
            await using var drop = admin.CreateCommand();
            drop.CommandText = $"DROP DATABASE IF EXISTS \"{databaseName}\"";
            await drop.ExecuteNonQueryAsync();
            NpgsqlConnection.ClearAllPools();
        }
    }
}
