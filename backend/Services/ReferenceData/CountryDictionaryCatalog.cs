    public static async Task<int> EnsureSeededAsync(PaymentContext context, CancellationToken ct = default)
    {
        var existingNames = await context.Countries
            .AsNoTracking()
            .Select(item => item.Name)
            .ToListAsync(ct);

        var known = new HashSet<string>(existingNames, StringComparer.OrdinalIgnoreCase);
        var missing = Items
            .Where(item => known.Add(item.Name))
            .Select(item => new CountryDictionaryItem
            {
                Name = item.Name,
                Description = item.Description,
                ColorHex = item.ColorHex,
                IsActive = true,
            })
            .ToList();

        if (missing.Count == 0)
        {
            return 0;
        }

        context.Countries.AddRange(missing);
        await context.SaveChangesAsync(ct);
        return missing.Count;
    }
