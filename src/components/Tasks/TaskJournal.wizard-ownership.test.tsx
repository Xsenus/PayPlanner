    expect(signals.every(signal => signal.aborted)).toBe(true);
    await act(async () => old.resolve({ clientId: 10, legalEntityId: null, clientCaseId: 100, clientCaseTitle: '', contracts: [{ id: 501, number: 'OLD-EDIT', title: '', date: '2026-11-01', billingMode: 'Fixed', status: 'Concluded' }] }));
