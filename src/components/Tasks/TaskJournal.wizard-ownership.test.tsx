    await waitFor(() => expect(options(field)).toContain('Текущее дело'));
    fireEvent.change(field, { target: { value: '100' } });
    fireEvent.click(await screen.findByTitle('Просмотр'));
    await screen.findByTestId('task-legacy-card-window');
    expect(apiMock.getCasesV1).toHaveBeenCalledTimes(2);
    authState.user = { ...authState.user, role: { id: 48 } };
    fireEvent.click(screen.getByRole('button', { name: 'Обновить роль для теста' }));
