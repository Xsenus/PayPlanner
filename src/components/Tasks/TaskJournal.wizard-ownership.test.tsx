    fireEvent.change(within(card).getByTestId('task-title-input'), { target: { value: 'Черновик привязки' } });
    fireEvent.click(within(card).getByRole('checkbox', { name: /Общая задача без контрагента/ }));
    fireEvent.click(within(card).getByRole('button', { name: /^(Контрагент|Выберите контрагента)$/ }));
